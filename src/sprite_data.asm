; PURPOSE : Original sprite bitmaps. Format of every sprite:
;           - 16 pixels per row, 1 byte per pixel (a palette colour index)
;           - rows are stored one after another, top row first
;           - 16 x 16 sprites = 16 rows = 256 bytes
;           - Super Mario 16 x 32 = 32 rows = 512 bytes
;           - colour 0 is TRANSPARENT and is never drawn
;           All sprites face RIGHT. DrawSprite mirrors them for facing left.
; COLOURS : default VGA palette numbers (same values as the COLOUR_ names in
;           const_engine.asm). Letters in the comments show the picture:
;           .=0 transparent   R=4 red     S=12 light red (skin)
;           B=1 blue          N=6 brown   Y=14 yellow    W=15 white
;           G=2 green         L=10 light green   D=8 dark grey
; NOTE    : If the colour numbers in const_engine.asm are changed later, the
;           numbers in this file must be changed to match.
; ==========================================================================

